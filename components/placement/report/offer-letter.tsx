export function OfferLetter({ pri }: { pri: number }) {
  const { persona, personaId, blueprint, lang } = useDemo()
  const letterRef = useRef<HTMLDivElement>(null)
  const dLang = lang === 'hi' ? 'hi' : 'en'
  const inst = institutionById(persona.institutionId)
  const drives = drivesFor(personaId)
  const earliest = drives[0]
  const band = bandFor(pri)
  const pattern = earliest?.blueprintId ? blueprintById(earliest.blueprintId).label : blueprint?.label
  const last4 = (persona.apaarMasked.match(/(\d{4})\s*$/) ?? [])[1] ?? '0000'
  const ref = `PS-SIM-${persona.avatarInitials}-${last4}-${DEMO_TODAY.replace(/-/g, '')}`

  return (
    <section id="offer" className="flex h-full scroll-mt-24 flex-col rounded-2xl border border-white/10 bg-white/[0.03] p-4 sm:p-5">
      <div className="flex flex-wrap items-start gap-3">
        <div className="min-w-[15rem] flex-1">
          <div className="flex items-center gap-2">
            <FileBadge2 className="h-4 w-4 text-cyan-300" aria-hidden />
            <Tr b={TXT.heading} as="h2" className="text-[15px] font-semibold text-white" />
          </div>
          <Tr b={TXT.sub} as="p" className="mt-1 text-[12.5px] leading-snug text-gray-400" />
        </div>
        <button
          type="button"
          onClick={() => printOnly(letterRef.current)}
          className="no-print inline-flex h-10 items-center gap-2 rounded-lg border border-white/15 bg-white/[0.05] px-3.5 text-[13px] font-semibold text-white transition-colors hover:border-cyan-300/50 hover:bg-cyan-400/10"
        >
          <Download className="h-4 w-4 text-cyan-300" aria-hidden />
          <Tr b={TXT.download} />
        </button>
      </div>

      {/* The printable letter: a white A4 card. printOnly() prints just this element. */}
      <div ref={letterRef} className="print-page mt-4 w-full p-5 text-gray-900 sm:p-8">
        <div className="relative overflow-hidden">
          {/* Diagonal watermark (prints: print-color-adjust is exact) */}
          <div aria-hidden className="pointer-events-none absolute inset-0 z-0 flex select-none items-center justify-center">
            <Tr
              b={{ en: 'Simulated · not an actual offer', hi: 'सिम्युलेटेड · असली ऑफ़र नहीं', hinglish: 'Simulated · asli offer nahi' }}
              className="-rotate-[26deg] whitespace-nowrap rounded-md border-[3px] border-rose-600/25 px-4 py-1.5 text-[22px] font-black uppercase tracking-[0.14em] text-rose-600/[0.16] sm:text-[34px]"
            />
          </div>

          <div className="relative z-10">
            <div className="flex flex-wrap items-start justify-between gap-3 border-b border-gray-200 pb-4">
              <div>
                <p className="bg-gradient-to-r from-blue-600 via-cyan-600 to-emerald-600 bg-clip-text text-[13px] font-bold uppercase tracking-[0.16em] text-transparent">
                  ParthSarthi Placement OS
                </p>
                <Tr b={TXT.letterTitle} as="h3" className="mt-1 text-[19px] font-bold leading-tight text-gray-900 sm:text-[21px]" />
              </div>
              <div className="text-right text-[12px] leading-relaxed text-gray-500">
                <p>
                  <Tr b={TXT.ref} />: <span className="font-mono text-gray-700">{ref}</span>
                </p>
                <p>
                  <Tr b={TXT.date} />: <span className="text-gray-700">{fmtDate(DEMO_TODAY, dLang, { year: true })}</span>
                </p>
              </div>
            </div>

            <div className="mt-4 text-[13.5px] leading-relaxed text-gray-700">
              <p className="text-[12px] font-semibold uppercase tracking-[0.12em] text-gray-500">
                <Tr b={TXT.to} />
              </p>
              <p className="mt-0.5 text-[15px] font-semibold text-gray-900">
                <Tr b={{ en: persona.name, hi: persona.nameHi }} />
              </p>
              <p>
                {persona.branchLabel}
                {inst ? ` · ${inst.name}` : ''}
              </p>
              <p className="text-[12px] text-gray-500">{persona.apaarMasked}</p>
            </div>

            <div className="mt-5 rounded-xl border-2 border-cyan-600/30 bg-cyan-50 px-4 py-4">
              <p className="text-[12px] font-semibold uppercase tracking-[0.12em] text-cyan-800">
                <Tr b={TXT.band} />
              </p>
              <Tr b={offerBandForPersona(persona.kind, pri).full} as="p" className="mt-1 text-[18px] font-bold leading-snug text-gray-900 sm:text-[20px]" />
              <p className="mt-1 text-[12px] text-gray-500">
                <Tr b={OFFER_BAND_NOTE} />
              </p>
            </div>

            <dl className="mt-4 grid gap-x-6 gap-y-3 text-[13px] sm:grid-cols-2">
              <div>
                <dt className="text-[12px] font-semibold uppercase tracking-[0.1em] text-gray-500">
                  <Tr b={TXT.role} />
                </dt>
                <dd className="mt-0.5 font-medium text-gray-900">
                  <Tr b={OFFER_ROLE[personaId]} />
                </dd>
              </div>
              <div>
                <dt className="text-[12px] font-semibold uppercase tracking-[0.1em] text-gray-500">
                  <Tr b={TXT.readiness} />
                </dt>
                <dd className="mt-0.5 font-medium text-gray-900">
                  PRI {pri} · <Tr b={band.label} />
                </dd>
              </div>
              {pattern && (
                <div>
                  <dt className="text-[12px] font-semibold uppercase tracking-[0.1em] text-gray-500">
                    <Tr b={TXT.pattern} />
                  </dt>
                  <dd className="mt-0.5 font-medium text-gray-900">{pattern}</dd>
                </div>
              )}
              {earliest && (
                <div>
                  <dt className="text-[12px] font-semibold uppercase tracking-[0.1em] text-gray-500">
                    <Tr b={TXT.earliest} />
                  </dt>
                  <dd className="mt-0.5 font-medium text-gray-900">
                    <Tr b={earliest.title} /> · {fmtDate(earliest.date, dLang)}
                  </dd>
                </div>
              )}
            </dl>

            <ul className="mt-5 space-y-1.5 border-t border-gray-200 pt-4 text-[12px] leading-snug text-gray-600">
              {CONDITIONS.map((c, i) => (
                <li key={i} className="flex gap-2">
                  <ShieldAlert className="mt-px h-3.5 w-3.5 shrink-0 text-rose-500" aria-hidden />
                  <Tr b={c} />
                </li>
              ))}
            </ul>

            <div className="mt-5 flex flex-wrap items-end justify-between gap-3 text-[12px] text-gray-500">
              <Tr b={TXT.issued} />
              <Tr b={TXT.review} className="text-gray-600" />
            </div>
          </div>
        </div>
      </div>
    </section>
  )
}
