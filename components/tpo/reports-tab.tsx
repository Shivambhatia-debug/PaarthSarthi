function BranchPlacement({ collegeId, className }: { collegeId: string; className?: string }) {
  const rows = useMemo(() => branchPlacementFor(collegeId), [collegeId])
  const totFinal = rows.reduce((s, r) => s + r.finalYear, 0)
  const totOffers = rows.reduce((s, r) => s + r.offers, 0)
  const placedAvg = totFinal > 0 ? rows.reduce((s, r) => s + r.placedPrev * r.finalYear, 0) / totFinal : 0
  const maxPlaced = Math.max(1, ...rows.map((r) => r.placedPrev))
  return (
    <TpoCard title={UI.branchTitle} sub={UI.branchSub} icon={Table2} className={className} actions={<IllustrativeChip compact />}>
      <div className="overflow-x-auto rounded-lg border border-white/[0.08]">
        <Table className="min-w-[520px] text-[13px]">
          <TableHeader>
            <TableRow className="border-white/10 hover:bg-transparent">
              {[UI.branch, UI.finalYear, UI.offers27, UI.placed26, UI.ctc].map((h, i) => (
                <TableHead key={i} className={cn('h-9 whitespace-nowrap px-3 text-[12px] font-medium text-gray-400', i > 0 && 'text-right')}>
                  <Tr b={h} />
                </TableHead>
              ))}
            </TableRow>
          </TableHeader>
          <TableBody>
            {rows.map((r) => (
              <TableRow key={r.branch} className="border-white/[0.06] hover:bg-white/[0.03]">
                <TableCell className="px-3 py-2.5 font-medium text-gray-100">
                  <Tr b={BRANCH_NAME[r.branch] ?? r.branch} />
                </TableCell>
                <TableCell className="px-3 py-2.5 text-right tabular-nums text-gray-300">{fmtIN(r.finalYear)}</TableCell>
                <TableCell className="px-3 py-2.5 text-right tabular-nums text-emerald-300">{fmtIN(r.offers)}</TableCell>
                <TableCell className="px-3 py-2.5">
                  <div className="flex items-center justify-end gap-2">
                    <div className="hidden h-1.5 w-16 overflow-hidden rounded-full bg-white/[0.07] sm:block">
                      <div className="h-full rounded-full bg-cyan-400/80" style={{ width: `${(r.placedPrev / maxPlaced) * 100}%` }} />
                    </div>
                    <span className="w-10 text-right tabular-nums text-gray-200">{fmtPct(r.placedPrev, 0)}</span>
                  </div>
                </TableCell>
                <TableCell className="whitespace-nowrap px-3 py-2.5 text-right tabular-nums text-gray-200">₹{fmtNum(r.medianCtc, 1)} LPA</TableCell>
              </TableRow>
            ))}
          </TableBody>
          <TableFooter className="border-white/10 bg-white/[0.03]">
            <TableRow className="hover:bg-transparent">
              <TableCell className="px-3 py-2.5 font-semibold text-white">
                <Tr b={UI.total} />
              </TableCell>
              <TableCell className="px-3 py-2.5 text-right font-semibold tabular-nums text-white">{fmtIN(totFinal)}</TableCell>
              <TableCell className="px-3 py-2.5 text-right font-semibold tabular-nums text-emerald-300">{fmtIN(totOffers)}</TableCell>
              <TableCell className="px-3 py-2.5 text-right font-semibold tabular-nums text-white">{fmtPct(placedAvg, 0)}</TableCell>
              <TableCell className="px-3 py-2.5 text-right text-gray-500">—</TableCell>
            </TableRow>
          </TableFooter>
        </Table>
      </div>
    </TpoCard>
  )
}

function NaacDialog({
  collegeId,
  inst,
  b,
  open,
  onOpenChange,
}: {
  collegeId: string
  inst: Institution
  b: BatchMetrics
  open: boolean
  onOpenChange: (o: boolean) => void
}) {
  const { t, lang } = useDemo()
  const ol: 'en' | 'hi' = lang === 'hi' ? 'hi' : 'en'
  const sheetRef = useRef<HTMLDivElement>(null)
  const placed = useMemo(() => offersFor(collegeId).filter((o) => o.status === 'Accepted' || o.status === 'Upgraded'), [collegeId])

  const print = () => printOnly(sheetRef.current)

  const csv = () => {
    const header = ['Year', 'Name of student placed', 'Programme graduated from', 'Name of the employer (sector)', 'Pay package band', 'Institution']
    const rows = placed.map((o) => [ACADEMIC_YEAR, o.name, programmeFor(o.branch).en, o.sector.en, o.band, inst.name])
    const ok = downloadText(`${slugFor(inst)}-naac-5-2-1-batch-2027.csv`, toCsv(header, rows))
    aiToast(
      t(
        ok
          ? { en: `NAAC 5.2.1 CSV downloaded: ${placed.length} placed students`, hi: `NAAC 5.2.1 CSV डाउनलोड: ${placed.length} प्लेस्ड छात्र` }
          : { en: 'Download blocked by the browser', hi: 'ब्राउज़र ने डाउनलोड रोका' },
      ),
      { tone: ok ? 'ok' : 'warn' },
    )
  }

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="z-[100] flex max-h-[92vh] w-[calc(100vw-1.5rem)] max-w-4xl flex-col gap-0 overflow-hidden rounded-2xl border-white/10 bg-[#0d1117] p-0 text-gray-100 sm:rounded-2xl">
        <DialogHeader className="border-b border-white/10 px-4 pb-4 pt-5 text-left sm:px-6">
          <DialogTitle className="flex flex-wrap items-center gap-2 pr-8 text-[18px] font-semibold text-white">
            <ShieldCheck aria-hidden className="h-5 w-5 text-cyan-300" />
            <Tr b={UI.naacTitle} />
            <AIBadge />
          </DialogTitle>
          <DialogDescription className="pr-8 text-[13px] text-gray-400">
            <Tr b={UI.dlgDesc} />
          </DialogDescription>
          <div className="flex flex-wrap gap-2 pt-2">
            <button type="button" onClick={print} className={btnAi}>
              <Printer aria-hidden className="h-4 w-4" />
              <Tr b={UI.print} />
            </button>
            <button type="button" onClick={csv} className={btnGhost}>
              <Download aria-hidden className="h-4 w-4" />
              <Tr b={UI.csv} />
            </button>
          </div>
        </DialogHeader>

        <div className="min-h-0 flex-1 overflow-y-auto overscroll-contain bg-[#0b0f16] p-3 sm:p-6">
          <div ref={sheetRef} className="print-page p-5 sm:p-10">
            <div className="flex flex-wrap items-start justify-between gap-3 border-b-2 border-gray-900 pb-3">
              <div className="min-w-0">
                <Tr as="p" b={UI.sheetSub} className="block text-[12px] font-semibold uppercase tracking-[0.12em] text-gray-500" />
                <Tr as="h2" b={UI.sheetTitle} className="mt-1 block text-[18px] font-bold leading-tight text-gray-900" />
                <p className="mt-1 text-[13px] font-medium text-gray-700">{inst.name}</p>
              </div>
              <div className="text-right text-[12px] text-gray-600">
                <p>
                  <Tr b={{ en: `Academic year ${ACADEMIC_YEAR}`, hi: `शैक्षणिक वर्ष ${ACADEMIC_YEAR}` }} />
                </p>
                <p>
                  <Tr b={{ en: 'Batch 2027 (final year)', hi: 'बैच 2027 (अंतिम वर्ष)' }} />
                </p>
                <p>{fmtDate(DEMO_TODAY, ol, { year: true })}</p>
              </div>
            </div>

            <div className="mt-3 grid grid-cols-3 gap-2 text-center text-[12px]">
              {[
                { v: b.finalYear, l: { en: 'Final-year students', hi: 'अंतिम वर्ष के छात्र' } as Bi },
                { v: b.offers, l: { en: 'Offers so far', hi: 'अब तक के ऑफ़र' } as Bi },
                { v: placed.length, l: { en: 'Rows in this sheet', hi: 'इस शीट की पंक्तियाँ' } as Bi },
              ].map((x, i) => (
                <div key={i} className="rounded border border-gray-300 px-2 py-1.5">
                  <p className="text-[16px] font-bold tabular-nums text-gray-900">{fmtIN(x.v)}</p>
                  <Tr as="p" b={x.l} className="block text-gray-600" />
                </div>
              ))}
            </div>

            <div className="mt-4 overflow-x-auto">
              <table className="w-full min-w-[560px] border-collapse text-left text-[12px] text-gray-900">
                <thead>
                  <tr className="bg-gray-100">
                    {[null, UI.colStudent, UI.colProg, UI.colEmployer, UI.colPkg, UI.colYear].map((h, i) => (
                      <th key={i} className="border border-gray-300 px-2 py-1.5 font-semibold">
                        {h ? <Tr b={h} /> : '#'}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  {placed.map((o, i) => (
                    <tr key={o.id}>
                      <td className="border border-gray-300 px-2 py-1.5 tabular-nums">{i + 1}</td>
                      <td className="border border-gray-300 px-2 py-1.5 font-medium">{o.name}</td>
                      <td className="border border-gray-300 px-2 py-1.5">
                        <Tr b={programmeFor(o.branch)} />
                      </td>
                      <td className="border border-gray-300 px-2 py-1.5">
                        <Tr b={o.sector} />
                      </td>
                      <td className="whitespace-nowrap border border-gray-300 px-2 py-1.5 tabular-nums">{o.band}</td>
                      <td className="border border-gray-300 px-2 py-1.5 tabular-nums">{ACADEMIC_YEAR}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>

            <div className="mt-8 grid grid-cols-2 gap-6 text-[12px] text-gray-700">
              <div className="border-t border-gray-400 pt-1.5">
                <Tr b={UI.preparedBy} />
              </div>
              <div className="border-t border-gray-400 pt-1.5 text-right">
                <Tr b={UI.verifiedBy} />
              </div>
            </div>
            <p className="mt-4 text-[12px] leading-snug text-gray-500">
              <Tr b={UI.footer} />
            </p>
          </div>
        </div>
      </DialogContent>
    </Dialog>
  )
}
