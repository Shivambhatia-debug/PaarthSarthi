function parseDemoUrl(): { host: string; path: string } {
  try {
    const u = new URL(PUBLIC_DEMO_URL)
    const path = u.pathname.replace(/\/+$/, '') || '/'
    return { host: u.host, path }
  } catch {
    return { host: PUBLIC_DEMO_URL, path: '/placement-os' }
  }
}

