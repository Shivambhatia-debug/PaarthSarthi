export interface QrCodeProps {
  size?: number
  /** 'dark' for the dark OS page, 'paper' for the white leave-behind. */
  tone?: 'dark' | 'paper'
  className?: string
}

/** Static QR PNG (generated by the integration unit). Falls back to a styled box if it is missing. */
export function QrCode({ size = 160, tone = 'dark', className }: QrCodeProps) {
  const [failed, setFailed] = useState(false)
  const paper = tone === 'paper'
  if (failed) {
    return (
      <div
        role="img"
        aria-label={`QR code for ${DEMO_LINK_TEXT}`}
        className={cn(
          'flex shrink-0 flex-col items-center justify-center gap-1.5 rounded-lg border-2 border-dashed text-center',
          paper ? 'border-slate-400 bg-slate-50 text-slate-700' : 'border-white/20 bg-white/[0.03] text-gray-300',
          className,
        )}
        style={{ width: size, height: size }}
      >
        <QrIcon className={cn('h-6 w-6', paper ? 'text-slate-500' : 'text-cyan-300')} aria-hidden />
        <span className="px-2 text-[12px] font-semibold leading-tight">QR → {DEMO_LINK.path}</span>
      </div>
    )
  }
  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={QR_IMAGE_PATH}
      width={size}
      height={size}
      alt={`QR code: ${DEMO_LINK_TEXT}`}
      onError={() => setFailed(true)}
      className={cn('shrink-0 rounded-lg bg-white', paper ? 'border border-slate-300 p-1' : 'p-2', className)}
      style={{ width: size, height: size }}
    />
  )
}

